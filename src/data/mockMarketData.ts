const TIMEFRAME_SECONDS: Record<Timeframe, number> = {
  '1m': 60,
  '5m': 300,
  '15m': 900,
  '30m': 1800,
  '1h': 3600,
  '4h': 14400,
  '1D': 86400,
  '1W': 604800,
  '1M': 2592000,
};

function seededRandom(seed: number): () => number {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return () => {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

export function generateCandlesForInstrument(
  instrument: Instrument,
  timeframe: Timeframe,
  count = 180
): Candle[] {
  const stepSec = TIMEFRAME_SECONDS[timeframe];
  const anchorTime = Math.floor(Date.UTC(2026, 10, 25, 10, 0, 0) / 1000);
  const symbolSeed = instrument.symbol
    .split('')
    .reduce((acc, ch, i) => acc + ch.charCodeAt(0) * (i + 17), 0);
  const tfSeed = timeframe.split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  const rand = seededRandom(symbolSeed * 31 + tfSeed * 13);

  const tfScale = Math.sqrt(stepSec / 3600);
  const baseVolPct =
    instrument.category === 'Crypto'
      ? 0.0085
      : instrument.category === 'Forex'
      ? 0.0014
      : instrument.category === 'Commodities'
      ? 0.0042
      : instrument.category === 'Indices'
      ? 0.0026
      : 0.0052;
  const vol = baseVolPct * Math.max(0.35, Math.min(2.8, tfScale));

  // Build prices backward from current price so the latest close equals instrument.price
  const closes: number[] = new Array(count);
  closes[count - 1] = instrument.price;
  const netBias = instrument.changePercent >= 0 ? 0.08 : -0.08;

  for (let i = count - 2; i >= 0; i--) {
    const wave = Math.sin(i * 0.14) * vol * 0.45 + Math.cos(i * 0.05) * vol * 0.35;
    const shock = (rand() - 0.5) * 2 * vol + netBias * vol * 0.25;
    const prev = closes[i + 1] / (1 + shock + wave * 0.25);
    closes[i] = Math.max(prev, instrument.price * 0.35);
  }

  const candles: Candle[] = [];
  const factor = Math.pow(10, instrument.decimals);
  const round = (n: number) => Math.round(n * factor) / factor;

  for (let i = 0; i < count; i++) {
    const close = round(closes[i]);
    const open = i === 0 ? round(close * (1 + (rand() - 0.5) * vol * 0.6)) : candles[i - 1].close;
    const wickUp = Math.abs((rand() * 0.85 + 0.1) * vol * close);
    const wickDown = Math.abs((rand() * 0.85 + 0.1) * vol * close);
    const high = round(Math.max(open, close) + wickUp);
    const low = round(Math.min(open, close) - wickDown);
    const baseVolume = Math.max(100, instrument.volume24h / 65);
    const rangeWeight = 1 + Math.abs(close - open) / Math.max(close * vol, 1e-9);
    const volume = Math.round(baseVolume * (0.45 + rand() * 1.1) * Math.min(rangeWeight, 2.4));

    candles.push({
      time: anchorTime - (count - 1 - i) * stepSec,
      open,
      high,
      low,
      close,
      volume,
    });
  }

  return candles;
}


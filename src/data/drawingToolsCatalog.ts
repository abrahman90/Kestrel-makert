export const ALL_DRAWING_TOOLS: DrawingToolDef[] = DRAWING_CATEGORIES.flatMap((c) => c.tools);

export function getDrawingToolDef(tool: DrawingTool): DrawingToolDef | null {
  if (tool === 'cursor') return null;
  return ALL_DRAWING_TOOLS.find((t) => t.id === tool) ?? null;
}

